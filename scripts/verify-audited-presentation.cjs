const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),read=file=>fs.readFileSync(path.join(root,file),'utf8');
const summary=require(path.join(root,'dist/record-summary.js'));
const data=JSON.parse(read('dist/data.js').replace(/^window.BORDER_DATA = /,'').replace(/;\s*$/,''));
const sc12=data.events.find(e=>e.id==='SC12');
const oldHash='622af8dd696310fc5f0987380195d3593fcc8f422fa77c58f9a598c39d5cb995';
const current=summary.describe({...sc12,event_hash:oldHash});
assert(!current.includes('252-day period'),'SC12 cannot revive the old operational-duration paragraph');
assert(current.includes('rule in force')&&current.includes('freight'),'audited policy scope and exceptions remain explicit');
assert.equal(current,summary.describe({...sc12,audit_current:true,audited_reader:undefined,event_hash:oldHash}),'compact audit flag preserves current summary');
const qualified={...sc12,audit_current:true,scope:'Old parent scope',official_rationale:'Old motive',duration_periods:[{scope:'Birch checkpoint passengers; freight and returning residents excepted.',measure_type:'formal_policy_period'}]};
const text=summary.describe(qualified);
assert(text.includes('passengers; freight and returning residents excepted.'),'a semicolon cannot discard an exception');
assert(!text.includes('Old parent scope')&&!text.includes('Old motive'),'legacy parent attributes cannot override audited phase scope');
assert(summary.describe(data.events.find(e=>e.id==='R16-AN-001')).includes('cargo could cross after transshipment'),'a freight-vehicle restriction must retain the cargo exception');

const sa025=data.events.find(e=>e.id==='SA025'),road=sa025.duration_periods.find(p=>p.period_id==='SA025-D1');
const rail=sa025.duration_periods.find(p=>p.analysis_included!==false);
assert(road&&rail&&road.analysis_included===false,'mixed included/reference record is retained');
assert(summary.describe(sa025).includes('rail freight'));
assert.equal(summary.describe(sa025),summary.describe(sa025,{periods:[rail]}),'excluded road stage does not enter the public summary');
const escape=value=>String(value??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const context={escape,escapeHTML:escape,cleanText:v=>String(v??''),phaseDates:()=> 'Recorded dates',phaseSourceLink:url=>escape(url),C:{measureLabel:()=> 'Recorded closure'},window:{},cardPeriodDates:()=> 'Recorded dates'};
vm.createContext(context);
const analysis=read('scripts/analysis-ui.js');
vm.runInContext(analysis.slice(analysis.indexOf('function phaseHTML('),analysis.indexOf('function sourceLink(')),context);
const datasetRoad=context.phaseHTML(road,[]),datasetRail=context.phaseHTML(rail,[]);
assert(datasetRoad.includes('<strong>Reference only'));
assert(datasetRoad.includes('Excluded from mapping and analysis'));
assert(datasetRoad.includes(escape(road.scope))&&datasetRoad.includes(escape(road.qualification)),'reference scope and evidence remain visible in dataset detail');
assert(!datasetRail.includes('<strong>Reference only'),'eligible rail stage is not excluded');
const app=read('dist/app.js');
vm.runInContext(app.slice(app.indexOf('  function periodLabel('),app.indexOf('  function cardSources(')),context);
vm.runInContext(app.slice(app.indexOf('  function cardPeriodHTML('),app.indexOf('  function locationRecordHTML(')),context);
assert(context.cardPeriodHTML(road).includes('Reference only'));
assert(context.cardPeriodHTML(road).includes('Excluded from mapping and analysis'));
assert(!context.cardPeriodHTML(rail).includes('Reference only'));
assert.equal(sa025.duration_periods.length,2,'presentation does not remove reference phases');
console.log('Audited presentation passed: stale hashes blocked, complete scope exceptions retained, eligible summaries isolated, reference-only phases visible and labelled in dataset and map details.');
